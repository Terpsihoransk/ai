-- Базовое расширение для векторного типа. Требуется ДО создания колонок vector(...).
CREATE EXTENSION IF NOT EXISTS vector;

-- =============================================
-- Основные таблицы чата (сущности Chat / ChatEntry)
-- =============================================

CREATE TABLE IF NOT EXISTS chat (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    title      VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS chat_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content    TEXT,
    role       VARCHAR(255)
        CONSTRAINT chat_entry_role_check
            CHECK (role IN ('USER', 'ASSISTANT')),
    started_at TIMESTAMP(6) NOT NULL
);

-- Join-таблица истории: Chat.history (@OneToMany без @JoinColumn).
CREATE TABLE IF NOT EXISTS chat_history (
    chat_id    BIGINT NOT NULL,
    history_id BIGINT NOT NULL,
    CONSTRAINT chat_history_history_id_key UNIQUE (history_id),
    CONSTRAINT fk_chat_history_chat FOREIGN KEY (chat_id) REFERENCES chat (id),
    CONSTRAINT fk_chat_history_entry FOREIGN KEY (history_id) REFERENCES chat_entry (id)
);

-- =============================================
-- RAG: загруженные документы (сущность LoadedDocument)
-- =============================================

CREATE TABLE IF NOT EXISTS loaded_document (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename      VARCHAR(255) NOT NULL,
    content_hash  VARCHAR(255) NOT NULL,
    document_type VARCHAR(255) NOT NULL,
    chunk_count   INTEGER,
    loaded_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_document UNIQUE (filename, content_hash)
);

-- =============================================
-- RAG: векторное хранилище (владелец схемы — Spring AI PgVectorStore)
-- Согласовано со свойствами spring.ai.vectorstore.pgvector.* в application.properties:
--   initialize-schema=false, dimensions=1024, id-type=text, distance-type=cosine-distance, index-type=hnsw
-- =============================================

CREATE TABLE IF NOT EXISTS vector_store (
    id        VARCHAR(255) PRIMARY KEY,
    content   TEXT,
    metadata  JSON,
    embedding VECTOR(1024)
);

-- =============================================
-- Индексы
-- =============================================

CREATE INDEX IF NOT EXISTS idx_loaded_documents_filename
    ON loaded_document (filename);

CREATE INDEX IF NOT EXISTS vector_store_hnsw_index
    ON vector_store USING hnsw (embedding vector_cosine_ops);
